// 支付服务协议、免密支付授权、联系人管理、心愿罐明细的演示主线（规则模式，不调模型）。
// 测试后端默认预签协议（PAYMENT_AGREEMENT_PRESIGNED），走协议流程的用例先撤回签署。
import { cards, chip, expect, say, settled, test } from './helpers.js'

async function passFaceAndSms(page, auth) {
  await auth.getByRole('button', { name: '模拟人脸识别' }).click()
  const sms = await auth.getByText(/验证码\d{6}/).textContent()
  await auth.getByPlaceholder('输入 6 位验证码').fill(sms.match(/验证码(\d{6})/)[1])
  await auth.getByRole('button', { name: '提交' }).click()
}

test('14 首次付款先签《支付服务协议》→ 原交易继续 → 回执后邀请开通免密 → 滚轮设额度 → 🔴 开通 → 额度内 🟡 免密、超额 🔴', async ({ page, request }) => {
  expect((await request.post('/dev/payment-agreement/reset')).ok()).toBeTruthy()

  await chip(page, '给我妈转500，备注生活费')
  const agreement = cards(page, 'payment-agreement-card')
  await expect(agreement).toContainText('向王*英（尾号1234）转账500.00元')
  await expect(agreement).toContainText('免密另行授权')
  await expect(cards(page, 'confirm-card')).toHaveCount(0) // 没同意之前不出确认卡
  await agreement.getByTestId('agreement-full-toggle').click()
  await expect(agreement.getByTestId('agreement-sections')).toContainText('适用范围')
  await agreement.getByTestId('agreement-sign').click()
  await settled(page)

  const confirm = cards(page, 'confirm-card')
  await expect(confirm).toContainText('🟡')
  await expect(confirm).toContainText('¥500.00')
  await confirm.getByRole('button', { name: '确认' }).click()
  await expect(cards(page, 'receipt-card')).toContainText('转账成功')

  const invite = cards(page, 'mandate-invite')
  await expect(invite).toContainText('要开通吗')
  await invite.getByTestId('mandate-open').click()
  await settled(page)

  const form = cards(page, 'mandate-card')
  await expect(form).toContainText('母亲 · 王*英')
  await expect(form.getByTestId('mandate-pay-card')).toHaveCount(2)
  const wheels = form.getByTestId('digit-wheel')
  await expect(wheels.nth(0).getByTestId('digit-wheel-value')).toContainText('500')
  await expect(wheels.nth(1).getByTestId('digit-wheel-value')).toContainText('2,000')
  await form.getByTestId('mandate-submit').click()
  await settled(page)

  const open = cards(page, 'confirm-card').nth(1)
  await expect(open).toContainText('开通免密支付确认')
  await expect(open).toContainText('🔴')
  await open.getByRole('button', { name: '确认' }).click()
  await passFaceAndSms(page, cards(page, 'auth-card'))
  await expect(cards(page, 'receipt-card').nth(1)).toContainText('开通免密支付成功')

  await say(page, '给我妹转300')
  const nopwd = cards(page, 'confirm-card').nth(2)
  await expect(nopwd).toContainText('🟡')
  await expect(nopwd.getByTestId('confirm-nopwd')).toContainText('免密支付 · 今日已用 0.00 / 2,000.00 元')
  await nopwd.getByRole('button', { name: '确认' }).click()
  await expect(cards(page, 'receipt-card').nth(2)).toContainText('转账成功')

  await say(page, '给我爱人转600')
  const over = cards(page, 'confirm-card').nth(3)
  await expect(over).toContainText('🔴')
  await expect(over).toContainText('免密授权不适用：超过单笔免密额度')
  await expect(over.getByTestId('confirm-nopwd')).toHaveCount(0)
})

test('15 联系人管理：解除妈妈的亲密关系 → 免密对她失效 → 重新绑定（刷脸即可）→ 新增、删除联系人', async ({ page }) => {
  await chip(page, '我的联系人')
  const list = cards(page, 'contacts-card')
  const mom = list.getByTestId('contact-item').filter({ hasText: '王*英' })
  await expect(mom).toContainText('父母 · 已验证')
  await mom.getByTestId('contact-unbind').click()
  await page.getByRole('dialog').getByRole('button', { name: '解除' }).click()
  await settled(page)
  const unbind = cards(page, 'confirm-card')
  await expect(unbind).toContainText('解除亲密关系确认')
  await expect(unbind).toContainText('🟡')
  await unbind.getByRole('button', { name: '确认' }).click()
  await expect(cards(page, 'receipt-card')).toContainText('解除亲密关系成功')

  await chip(page, '我的联系人')
  const list2 = cards(page, 'contacts-card').nth(1)
  const mom2 = list2.getByTestId('contact-item').filter({ hasText: '王*英' })
  await expect(mom2).not.toContainText('已验证')
  await mom2.getByTestId('contact-bind').click()
  await page.locator('.van-action-sheet').getByText('父母', { exact: true }).click()
  await settled(page)
  const bind = cards(page, 'confirm-card').nth(1)
  await expect(bind).toContainText('绑定亲密关系确认')
  await expect(bind).toContainText('确认后完成人脸识别即可，也可改用短信验证码')
  await bind.getByRole('button', { name: '确认' }).click()
  await cards(page, 'auth-card').getByRole('button', { name: '模拟人脸识别' }).click()
  await expect(cards(page, 'receipt-card').nth(1)).toContainText('绑定亲密关系成功')

  await chip(page, '我的联系人')
  const list3 = cards(page, 'contacts-card').nth(2)
  await expect(list3.getByTestId('contact-item').filter({ hasText: '王*英' })).toContainText('父母 · 已验证')
  await list3.getByTestId('contact-add').click()
  const form = page.getByTestId('contact-form')
  await form.getByTestId('contact-name').locator('input').fill('孙小明')
  await form.getByTestId('contact-account').locator('input').fill('6222020200112233')
  await form.getByText('建设银行', { exact: true }).click()
  await form.getByTestId('contact-phone').locator('input').fill('13900001111')
  await form.getByTestId('contact-submit').click()
  await settled(page)
  const add = cards(page, 'confirm-card').nth(2)
  await expect(add).toContainText('添加联系人确认')
  await expect(add).toContainText('尾号 2233')
  await expect(add).not.toContainText('6222020200112233') // 完整卡号不上确认卡
  await add.getByRole('button', { name: '确认' }).click()
  await expect(cards(page, 'receipt-card').nth(2)).toContainText('成功')

  await chip(page, '我的联系人')
  const list4 = cards(page, 'contacts-card').nth(3)
  const sun = list4.getByTestId('contact-item').filter({ hasText: '尾号 2233' })
  await expect(sun).toHaveCount(1)
  await sun.getByTestId('contact-delete').click()
  await page.getByRole('dialog').getByRole('button', { name: '删除' }).click()
  await settled(page)
  await cards(page, 'confirm-card').nth(3).getByRole('button', { name: '确认' }).click()
  await expect(cards(page, 'receipt-card').nth(3)).toContainText('删除联系人成功')
})

