"""反诈话术识别（F-TR-08）。只看用户自己说的话：命中后由策略引擎升到 🔴 并启动冷静期。

关键词按常见电信网络诈骗类型整理，是演示用的规则，不是完整的风控模型。
"""

import re
from dataclasses import dataclass, field

# 类型、给用户的提示、话术特征
_SCRIPTS = [
    ("冒充公检法", "公检法机关不会通过电话办案，更没有所谓的「安全账户」",
     re.compile(r"安全[账帐]户|公检法|涉嫌(?:洗钱|犯罪|诈骗|违法)|资金(?:核查|清查|审查)|配合调查"
                r"|(?:公安|警察|警官|民警|检察|法院|法官).{0,15}(?:转账|转钱|汇款|打款|转到|转入|资金|[账帐]户|涉案|洗钱|通缉|逮捕|冻结)")),
    ("刷单返利", "刷单本身违法，「先垫付、再返利」是最常见的诈骗",
     re.compile(r"刷单|返利|刷信誉|做任务.{0,8}(?:垫付|佣金|返)|垫付.{0,8}(?:佣金|返还|本金)|点赞.{0,6}佣金")),
    ("贷款保证金", "正规贷款放款前不会收保证金、解冻费",
     re.compile(r"(?:贷款|放款|解冻|提现|激活).{0,10}(?:保证金|手续费|解冻费|验资)|(?:保证金|解冻费|验资).{0,10}(?:贷款|放款|解冻|提现)"
                r"|流水不足|刷流水")),
    ("冒充客服", "官方客服退款、理赔都不需要你转账",
     re.compile(r"(?:客服|快递|淘宝|京东|抖音|拼多多).{0,10}(?:退款|理赔|赔偿)|注销.{0,6}(?:校园贷|网贷|学生贷)"
                r"|关闭.{0,6}(?:百万保障|微信保障)|征信.{0,4}(?:修复|受损|有问题)")),
    ("共享屏幕", "不要向任何人共享屏幕或开启远程协助",
     re.compile(r"屏幕共享|共享屏幕|远程(?:协助|控制)")),
    ("虚假投资", "「稳赚不赔」「导师带单」多是投资诈骗",
     re.compile(r"稳赚不赔|内幕消息|带单(?:老师|导师)|投资导师|保本高收益")),
    ("中奖缴费", "中奖要先交钱的都是诈骗",
     re.compile(r"(?:中奖|领奖|奖金).{0,10}(?:手续费|税|保证金|先交)")),
]
_URGENT = re.compile(r"马上|立刻|立即|赶紧|赶快|快点|尽快|来不及|十万火急|别告诉|不要告诉|不能告诉|保密")
COMBO = "陌生账户大额催促"  # PRD：「新收款人 + 大额 + 催促」的组合
_COMBO_TIP = "对方催你马上向陌生账户转一大笔钱，请先停下来核实"
HOTLINE = "96110"


@dataclass
class FraudScan:
    hits: list[str] = field(default_factory=list)  # 命中的诈骗类型
    urgent: bool = False  # 有催促、要求保密的说法（单独出现不算命中，要和新收款人 + 大额组合）


def scan(texts: list[str]) -> FraudScan:
    """逐条检查用户原话；特征不跨消息拼接。"""
    hits = [label for label, _, pat in _SCRIPTS if any(pat.search(t) for t in texts)]
    return FraudScan(hits, any(_URGENT.search(t) for t in texts))


def warning(hits: list[str]) -> str:
    tips = [tip for label, tip, _ in _SCRIPTS if label in hits] + ([_COMBO_TIP] if COMBO in hits else [])
    return f"这笔转账疑似诈骗（{'、'.join(hits)}）：{'；'.join(tips)}。冷静期内不能确认，可拨打 {HOTLINE} 反诈专线核实。"
