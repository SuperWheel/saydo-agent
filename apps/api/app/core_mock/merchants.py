def merchant_by_alias(word: str) -> str | None:
    """用户说的商户简称 → 登记商户规范名。用户原话是可信的，这里只做查表。"""
    w = word.strip().lower()
    if not w:
        return None
    for name, aliases in MERCHANTS.items():
        if w == name.lower() or w in aliases:
            return name
    return None
